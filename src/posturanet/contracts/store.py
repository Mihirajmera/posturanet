"""Read and write contract YAML in the repo (design system section 5).

Approved contracts are never overwritten. On regeneration of a draft, human-added `owner`
and `ref` fields on matching entries are kept.
"""

from __future__ import annotations

import io
import re
from pathlib import Path
from typing import Any

from pydantic import ValidationError
from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap, CommentedSeq
from ruamel.yaml.error import YAMLError

from posturanet.errors import StageStop
from posturanet.models import BehaviorContract, NetRule

HEADER = "Generated by PosturaNet. Review must_allow and needs_review, then merge to approve."
_KEY_ORDER = (
    "schema",
    "resource",
    "account",
    "region",
    "kind",
    "observed",
    "must_allow",
    "must_deny",
    "needs_review",
    "unknown_risk",
    "status",
    "approved_by",
    "approved_at",
    "generated_by",
)
_RULE_ORDER = ("cidr", "port", "proto", "period", "owner", "ref", "count")


def contract_filename(address: str) -> str:
    return re.sub(r'[\[\]"]', "_", address) + ".yaml"


def contract_path(repo: Path, contracts_dir: str, address: str) -> Path:
    return repo / contracts_dir / contract_filename(address)


def load_contract(path: Path) -> BehaviorContract | None:
    if not path.is_file():
        return None
    try:
        data = YAML(typ="safe").load(path.read_text(encoding="utf-8"))
        return BehaviorContract.model_validate(data)
    except (YAMLError, ValidationError) as exc:
        raise StageStop(
            "contract",
            f"contract {path.name} is invalid",
            ["fix the YAML by hand, or delete it to regenerate a draft"],
            why=str(exc).splitlines()[0],
        ) from exc


def merge_human_fields(new: BehaviorContract, old: BehaviorContract | None) -> BehaviorContract:
    if old is None:
        return new
    kept = {(r.cidr, r.port, r.proto): r for r in [*old.must_allow, *old.needs_review]}

    def carry(rules: list[NetRule]) -> list[NetRule]:
        out = []
        for r in rules:
            prev = kept.get((r.cidr, r.port, r.proto))
            if prev is not None:
                r = r.model_copy(update={"owner": prev.owner or r.owner, "ref": prev.ref or r.ref})
            out.append(r)
        return out

    return new.model_copy(
        update={"must_allow": carry(new.must_allow), "needs_review": carry(new.needs_review)}
    )


def _flow(rule: NetRule) -> CommentedMap:
    data = rule.model_dump(exclude_none=True)
    m = CommentedMap((k, data[k]) for k in _RULE_ORDER if k in data)
    m.fa.set_flow_style()
    return m


def _seq(rules: list[NetRule]) -> CommentedSeq:
    s = CommentedSeq(_flow(r) for r in rules)
    if not rules:
        s.fa.set_flow_style()
    return s


def dump_contract(contract: BehaviorContract) -> str:
    data: dict[str, Any] = contract.model_dump(by_alias=True, mode="python")
    root = CommentedMap()
    for key in _KEY_ORDER:
        value = data[key]
        if key in ("must_allow", "must_deny", "needs_review"):
            value = _seq(getattr(contract, key))
        elif key == "observed":
            obs = CommentedMap(
                [
                    ("source", value["source"]),
                    ("window", CommentedMap(value["window"])),
                    ("confidence", str(value["confidence"])),
                ]
            )
            obs["window"].fa.set_flow_style()
            value = obs
        elif key == "account" and value is not None:
            value = str(value)
        root[key] = value
    root.yaml_set_start_comment(HEADER)

    yaml = YAML()
    yaml.indent(mapping=2, sequence=4, offset=2)
    yaml.width = 200
    buf = io.StringIO()
    yaml.dump(root, buf)
    text = buf.getvalue()
    # Quote the account id so YAML never reads it as a number.
    if contract.account:
        text = text.replace(f"account: {contract.account}\n", f'account: "{contract.account}"\n')
        text = text.replace(f"account: '{contract.account}'\n", f'account: "{contract.account}"\n')
    return text


def write_contract(path: Path, contract: BehaviorContract) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_contract(contract), encoding="utf-8", newline="\n")
