"""Contract kind `iam` (FR-51, architecture doc 14.3).

`must_allow` lists the actions the policy keeps: used actions from last-accessed data, plus
any a human adds (`source: human`) for rare jobs the data can't show. `reviewed_services`
lists services whose full action list a human confirmed (needed for data-plane services
such as S3, whose object actions aren't in last-accessed data). Merge the file to approve it.
"""

from __future__ import annotations

import io
from datetime import date
from pathlib import Path
from typing import Any

from pydantic import ValidationError
from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap, CommentedSeq
from ruamel.yaml.error import YAMLError

from posturanet import __version__
from posturanet.errors import StageStop
from posturanet.models.contract import ObservedMeta, ObservedWindow
from posturanet.models.iam import IamAllowed, IamApproval, IamContract, IamEvidence

HEADER = (
    "Generated by PosturaNet. Review must_allow: add actions rare jobs need (source: human),\n"
    "and list services you have fully reviewed in reviewed_services. Merge to approve."
)
_ALLOWED_ORDER = ("action", "last_seen", "source", "owner", "ref")


def build(
    ev: IamEvidence,
    *,
    resource: str,
    account: str | None,
    removed: list[str],
    blockers: list[str],
    today: date,
) -> IamContract:
    start = ev.created or today
    return IamContract(
        resource=resource,
        account=account,
        policy_arn=ev.policy_arn,
        observed=ObservedMeta(
            source=ev.source,
            window=ObservedWindow(start=start, end=today, days=ev.age_days),
            confidence=ev.confidence,
        ),
        principals=ev.principals,
        must_allow=[IamAllowed(action=u.action, last_seen=u.last_seen) for u in ev.used()],
        must_remove=sorted(set(removed)),
        needs_review=blockers,
        unknown_risk=(
            "Actions a principal hasn't used within IAM's tracking period (about 400 days) are "
            "removed; add any a rare job needs to must_allow. Denied attempts count as use, so "
            "must_allow may list actions another control already denies. iam:PassRole isn't "
            "tracked at all."
        ),
        generated_by=f"posturanet {__version__}",
    )


def approved_extras(contract: IamContract | None) -> tuple[frozenset[str], list[str]]:
    """(reviewed services, human-added actions) from an approved contract."""
    if contract is None or contract.status != "approved":
        return frozenset(), []
    extra = [a.action for a in contract.must_allow if a.source == "human"]
    return frozenset(s.lower() for s in contract.reviewed_services), extra


def approve(contract: IamContract, approval: IamApproval) -> IamContract:
    """Apply what a person approved at the terminal, as if they had edited the file."""
    have = {a.action for a in contract.must_allow}
    added = [
        IamAllowed(action=a, source="human", owner=approval.by)
        for a in approval.keep
        if a not in have
    ]
    return contract.model_copy(
        update={
            "must_allow": [*contract.must_allow, *added],
            "reviewed_services": sorted({*contract.reviewed_services, *approval.reviewed_services}),
            "status": "approved",
            "approved_by": approval.by,
            "approved_at": approval.at,
        }
    )


def merge(new: IamContract, old: IamContract | None) -> IamContract:
    """Keep what a human wrote in a draft: owners, refs, added actions, reviewed services."""
    if old is None:
        return new
    prev = {a.action: a for a in old.must_allow}
    allowed = [
        a.model_copy(update={"owner": prev[a.action].owner, "ref": prev[a.action].ref})
        if a.action in prev
        else a
        for a in new.must_allow
    ]
    have = {a.action for a in allowed}
    allowed += [a for a in old.must_allow if a.source == "human" and a.action not in have]
    return new.model_copy(
        update={
            "must_allow": sorted(allowed, key=lambda a: a.action.lower()),
            "reviewed_services": sorted(set(old.reviewed_services)),
        }
    )


def load(path: Path) -> IamContract | None:
    if not path.is_file():
        return None
    try:
        data = YAML(typ="safe").load(path.read_text(encoding="utf-8"))
        return IamContract.model_validate(data)
    except (YAMLError, ValidationError) as exc:
        raise StageStop(
            "contract",
            f"contract {path.name} is invalid",
            ["fix the YAML by hand, or delete it to regenerate a draft"],
            why=str(exc).splitlines()[0],
        ) from exc


def dump(contract: IamContract) -> str:
    data: dict[str, Any] = contract.model_dump(by_alias=True, mode="json")
    root = CommentedMap()
    for key, value in data.items():
        if key == "must_allow":
            seq = CommentedSeq()
            for a in contract.must_allow:
                d = a.model_dump(mode="json", exclude_none=True)
                m = CommentedMap((k, d[k]) for k in _ALLOWED_ORDER if k in d)
                m.fa.set_flow_style()
                seq.append(m)
            if not contract.must_allow:
                seq.fa.set_flow_style()
            value = seq
        elif key == "observed":
            obs = CommentedMap(value)
            obs["window"] = CommentedMap(value["window"])
            obs["window"].fa.set_flow_style()
            value = obs
        elif isinstance(value, list):
            seq = CommentedSeq(value)
            if not value:
                seq.fa.set_flow_style()
            value = seq
        root[key] = value
    root.yaml_set_start_comment(HEADER)
    yaml = YAML()
    yaml.indent(mapping=2, sequence=4, offset=2)
    yaml.width = 200
    buf = io.StringIO()
    yaml.dump(root, buf)
    text = buf.getvalue()
    if contract.account:
        for quote in ("", "'"):
            text = text.replace(
                f"account: {quote}{contract.account}{quote}\n", f'account: "{contract.account}"\n'
            )
    return text


def write(path: Path, contract: IamContract) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump(contract), encoding="utf-8", newline="\n")
