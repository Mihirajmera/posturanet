"""Contract kind `s3_public` (FR-50, architecture doc 14.2).

Lists who uses the bucket today and must keep working (`must_keep`), what the fix blocks
(`must_block`), and requesters PosturaNet can't tie to an account (`needs_review`). A human
moves a reviewed requester from `needs_review` to `must_keep` and merges the file to approve
it. Anonymous or cross-account-via-public-policy use is never approved away: it stops the fix.
"""

from __future__ import annotations

import io
from datetime import date
from pathlib import Path
from typing import Any

from pydantic import ValidationError
from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap, CommentedSeq
from ruamel.yaml.error import YAMLError

from posturanet import __version__
from posturanet.errors import StageStop
from posturanet.models.contract import ObservedMeta, ObservedWindow
from posturanet.models.s3 import S3Contract, S3Evidence, S3Use

HEADER = (
    "Generated by PosturaNet. Review must_keep and needs_review: move a requester you have\n"
    "confirmed from needs_review to must_keep, then merge to approve."
)
_USE_ORDER = ("requester", "kind", "operations", "count", "last_seen", "owner", "ref")


def build(
    ev: S3Evidence, *, resource: str, account: str | None, region: str | None, today: date
) -> S3Contract:
    start = date.fromordinal(today.toordinal() - ev.window_days)
    keep = sorted((u for b in ev.buckets for u in b.keeps), key=lambda u: u.requester)
    review = sorted((u for b in ev.buckets for u in b.needs_review), key=lambda u: u.requester)
    risk = (
        "Requests that failed to log, and object ACLs, are not visible here; Block Public "
        "Access ignores public object ACLs either way."
    )
    return S3Contract(
        resource=resource,
        account=account,
        region=region,
        observed=ObservedMeta(
            source=ev.source,
            window=ObservedWindow(start=start, end=today, days=ev.window_days),
            confidence=ev.confidence,
        ),
        exposure={b.bucket: b.exposure for b in ev.buckets},
        must_keep=keep,
        needs_review=review,
        unknown_risk=risk,
        generated_by=f"posturanet {__version__}",
    )


def reviewed(contract: S3Contract | None) -> set[str]:
    """Requesters a human approved as legitimate (approved contracts only)."""
    if contract is None or contract.status != "approved":
        return set()
    return {u.requester for u in contract.must_keep}


def merge(new: S3Contract, old: S3Contract | None) -> S3Contract:
    if old is None:
        return new
    kept = {u.requester: u for u in [*old.must_keep, *old.needs_review]}

    def carry(uses: list[S3Use]) -> list[S3Use]:
        out = []
        for u in uses:
            prev = kept.get(u.requester)
            if prev is not None:
                u = u.model_copy(update={"owner": prev.owner or u.owner, "ref": prev.ref or u.ref})
            out.append(u)
        return out

    return new.model_copy(
        update={"must_keep": carry(new.must_keep), "needs_review": carry(new.needs_review)}
    )


def load(path: Path) -> S3Contract | None:
    if not path.is_file():
        return None
    try:
        data = YAML(typ="safe").load(path.read_text(encoding="utf-8"))
        return S3Contract.model_validate(data)
    except (YAMLError, ValidationError) as exc:
        raise StageStop(
            "contract",
            f"contract {path.name} is invalid",
            ["fix the YAML by hand, or delete it to regenerate a draft"],
            why=str(exc).splitlines()[0],
        ) from exc


def _uses(uses: list[S3Use]) -> CommentedSeq:
    seq = CommentedSeq()
    for u in uses:
        d = u.model_dump(mode="json", exclude_none=True)
        m = CommentedMap((k, d[k]) for k in _USE_ORDER if k in d)
        m.fa.set_flow_style()
        seq.append(m)
    if not uses:
        seq.fa.set_flow_style()
    return seq


def dump(contract: S3Contract) -> str:
    data: dict[str, Any] = contract.model_dump(by_alias=True, mode="json")
    root = CommentedMap()
    for key, value in data.items():
        if key in ("must_keep", "needs_review"):
            value = _uses(getattr(contract, key))
        elif key == "observed":
            obs = CommentedMap(value)
            obs["window"] = CommentedMap(value["window"])
            obs["window"].fa.set_flow_style()
            value = obs
        elif key == "exposure":
            exp = CommentedMap()
            for name in sorted(value):
                row = CommentedMap(value[name])
                row.fa.set_flow_style()
                exp[name] = row
            value = exp
        elif key == "must_block":
            value = CommentedSeq(value)
        root[key] = value
    root.yaml_set_start_comment(HEADER)
    yaml = YAML()
    yaml.indent(mapping=2, sequence=4, offset=2)
    yaml.width = 200
    buf = io.StringIO()
    yaml.dump(root, buf)
    text = buf.getvalue()
    if contract.account:  # keep the account id a string
        for quote in ("", "'"):
            text = text.replace(
                f"account: {quote}{contract.account}{quote}\n", f'account: "{contract.account}"\n'
            )
    return text


def write(path: Path, contract: S3Contract) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump(contract), encoding="utf-8", newline="\n")
