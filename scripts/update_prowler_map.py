"""Regenerate `src/posturanet/ingest/prowler_checks.json` from Prowler's compliance data.

Prowler maps each of its checks to AWS Foundational Security Best Practices controls (the
Security Hub control ids PosturaNet uses) in
`prowler/compliance/aws/aws_foundational_security_best_practices_aws.json` (Apache-2.0).
Download that file yourself, then:

    python scripts/update_prowler_map.py path/to/fsbp.json 5.48.0

No network access here: the script only reads the file you pass.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "posturanet" / "ingest" / "prowler_checks.json"


def build(doc: dict[str, object], version: str) -> dict[str, object]:
    checks: dict[str, set[str]] = {}
    for req in doc["Requirements"]:  # type: ignore[union-attr]
        for check in req.get("Checks") or []:
            checks.setdefault(str(check), set()).add(str(req["Id"]))
    return {
        "_comment": (
            "Prowler check id -> AWS Foundational Security Best Practices control ids. "
            "Generated by scripts/update_prowler_map.py from Prowler's compliance data "
            "(Apache-2.0). Do not edit by hand."
        ),
        "_prowler_version": version,
        "checks": {k: sorted(v) for k, v in sorted(checks.items())},
    }


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    doc = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    OUT.write_text(json.dumps(build(doc, sys.argv[2]), indent=2) + "\n", "utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
